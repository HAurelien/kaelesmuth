#!/usr/bin/env python3
"""Check the Kaelesmuth vault against its schema (_tools/schema.json).

    python3 _tools/check_vault.py               report errors and warnings
    python3 _tools/check_vault.py --errors-only only errors
    python3 _tools/check_vault.py --strict      warnings also fail
    python3 _tools/check_vault.py --json        machine-readable report
    python3 _tools/check_vault.py --write-docs  regenerate the tables in Schema.md

Exit code 1 when there are errors (or warnings with --strict). The
pre-commit hook in _tools/hooks runs it before every commit.

Errors are things tools can't work with: broken links, wrong value types,
dates that contradict their year, a missing calendar. Warnings are things
that look wrong but may be intended: a link to the wrong kind of note, a
character in an event before they were born, a property not in the schema.
"""

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vault import Vault, link_target, body_links, parse_date, norm  # noqa: E402

ERROR, WARNING = "error", "warning"
DOCS_START = "<!-- schema-tables:start (generated by _tools/check_vault.py --write-docs; edit _tools/schema.json instead) -->"
DOCS_END = "<!-- schema-tables:end -->"


class Report:
    def __init__(self):
        self.items = []

    def add(self, severity, note, message, prop=None):
        self.items.append({
            "severity": severity,
            "file": note if isinstance(note, str) else note.rel,
            "property": prop,
            "message": message,
        })

    def error(self, note, message, prop=None):
        self.add(ERROR, note, message, prop)

    def warn(self, note, message, prop=None):
        self.add(WARNING, note, message, prop)


def is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def empty(v):
    return v is None or v == "" or v == []


def fmt_year(y, cal):
    return "%s (%s)" % (y, cal) if cal else str(y)


# ---------------------------------------------------------------- properties

def check_value(vault, report, note, key, spec, value):
    """Check one property value against its spec. Returns nothing."""
    sev = WARNING if spec.get("legacy") else ERROR
    t = spec["type"]
    if empty(value):
        return
    if t == "int":
        if not is_int(value):
            report.add(sev, note, "'%s' must be a whole number, got %r" % (key, value), key)
    elif t == "bool":
        if not isinstance(value, bool):
            report.add(sev, note, "'%s' must be true or false, got %r" % (key, value), key)
    elif t == "text":
        if isinstance(value, list):
            report.add(sev, note, "'%s' must be a single value, not a list" % key, key)
    elif t == "date":
        if parse_date(value) is None:
            report.add(sev, note, "'%s' must look like Y, Y-MM, Y-MM-DD or 'Y-MM-DD HH:MM', got %r" % (key, value), key)
        else:
            y, mo, d, h, mi = parse_date(value)
            if (mo is not None and not 1 <= mo <= 99) or (h is not None and not 0 <= h <= 99):
                report.add(sev, note, "'%s' has an out-of-range part: %r" % (key, value), key)
            ref = spec.get("refines")
            if ref:
                ref_val = note.get(ref)
                if empty(ref_val):
                    report.add(sev, note, "'%s' is set but '%s' is empty; set '%s: %d'" % (key, ref, ref, y), key)
                elif is_int(ref_val) and ref_val != y:
                    report.add(sev, note, "'%s' (%s) is not in year '%s' (%s)" % (key, value, ref, ref_val), key)
    elif t == "enum":
        values = vault.enum_values(spec, key)
        if values is not None and value not in values:
            report.add(sev, note, "'%s' must be one of %s, got %r" % (key, ", ".join(values), value), key)
    elif t == "list":
        if not isinstance(value, list):
            report.add(sev, note, "'%s' must be a list" % key, key)
    elif t in ("link", "links"):
        if t == "link" and isinstance(value, list):
            if len(value) == 1:
                value = value[0]
            else:
                report.add(sev, note, "'%s' takes a single link, not a list" % key, key)
                return
        values = value if isinstance(value, list) else [value]
        if t == "links" and not isinstance(value, list):
            report.add(sev, note, "'%s' must be a list of links: %s: [\"%s\"]" % (key, key, value), key)
        allowed = spec.get("to", ["*"])
        for v in values:
            if empty(v):
                continue
            target = link_target(v)
            if target is None:
                report.add(sev, note, "'%s' must hold links like \"[[Name]]\", got %r" % (key, v), key)
                continue
            dest = vault.resolve(target)
            if dest is None:
                report.add(sev, note, "'%s' links to [[%s]], which doesn't exist" % (key, target), key)
            elif "*" not in allowed and dest.type not in allowed:
                report.warn(note, "'%s' should link to: %s; but [[%s]] is: %s" % (
                    key, ", ".join(allowed), target, dest.type or "no type"), key)


def check_note(vault, report, note):
    if note.parse_error:
        report.error(note, "properties can't be read (line %d): %s" % (note.parse_error.line, note.parse_error))
        return
    if not note.has_frontmatter:
        report.error(note, "no properties block; every note needs at least 'type'")
        return
    t = note.type
    if empty(t):
        report.error(note, "missing 'type'", "type")
        return
    ts = vault.type_schema(t)
    if ts is None:
        report.error(note, "unknown type %r; known types: %s" % (t, ", ".join(vault.schema["types"])), "type")
        return
    if note.folder != ts["folder"]:
        report.error(note, "a %s belongs in %s" % (t, ts["folder"] + "/" if ts["folder"] else "the vault root"), "type")
    specs = ts["properties"]
    for key, spec in specs.items():
        if spec.get("required") and empty(note.get(key)):
            report.error(note, "missing '%s'" % key, key)
    for key, value in note.props.items():
        if key in ts["forbidden"]:
            report.error(note, "'%s' is not used: %s" % (key, ts["forbidden"][key]), key)
        elif key not in specs:
            report.warn(note, "'%s' is not in the schema for %s notes" % (key, t), key)
        else:
            check_value(vault, report, note, key, specs[key], value)
    check_calendar(vault, report, note, ts)
    check_span(vault, report, note, ts)


def check_calendar(vault, report, note, ts):
    """Any note with a year needs a calendar, and the calendar's planet
    should be one of the note's planets."""
    specs = ts["properties"]
    if "calendar" not in specs:
        return
    year_keys = [k for k, s in specs.items() if s["type"] in ("int", "date") and k not in ("calendar",)]
    has_year = any(not empty(note.get(k)) for k in year_keys)
    cal = note.get("calendar")
    if has_year and empty(cal):
        report.error(note, "has a year but no 'calendar'", "calendar")
    planets = [link_target(p) for p in (note.get("planet") or []) if link_target(p)]
    if has_year and isinstance(cal, str) and cal in vault.schema["calendars"] and planets:
        cal_planet = vault.schema["calendars"][cal]["planet"]
        if norm(cal_planet) not in {norm(p) for p in planets}:
            report.warn(note, "dated in the %s calendar but not set on planet %s" % (cal, cal_planet), "calendar")


def check_span(vault, report, note, ts):
    span = ts["span"]
    if not span:
        return
    s, e = note.get(span["start"]), note.get(span["end"])
    if is_int(s) and is_int(e) and e < s:
        report.error(note, "'%s' (%d) is before '%s' (%d)" % (span["end"], e, span["start"], s), span["end"])
    if note.type == "event":
        if not empty(note.get("end_year")) and empty(note.get("year")):
            report.error(note, "'end_year' is set but 'year' is empty", "end_year")
        if note.get("approximate") is True and empty(note.get("year")):
            report.warn(note, "'approximate' is true but there is no year", "approximate")
        d1, d2 = parse_date(note.get("date")), parse_date(note.get("end_date"))
        if d1 and d2 and tuple(x or 0 for x in d2) < tuple(x or 0 for x in d1):
            report.error(note, "'end_date' is before 'date'", "end_date")


# ---------------------------------------------------------------- cross-note

def check_events(vault, report):
    events = vault.of_type("event")
    for ev in events:
        if ev.parse_error:
            continue
        cal = ev.get("calendar")
        start, end = vault.span(ev)
        approx = ev.get("approximate") is True
        # participants alive at the time
        if start is not None:
            for p in ev.get("participants") or []:
                who = vault.resolve_link(p)
                if who is None or who.type not in ("character", "god"):
                    continue
                if who.get("calendar") != cal:
                    continue  # different calendars can't be compared yet
                born, died = who.get("born"), who.get("died")
                tag = " (event year is approximate)" if approx else ""
                if is_int(born) and end is not None and end < born:
                    report.warn(ev, "[[%s]] takes part in %s but is born in %s%s" % (
                        who.name, fmt_year(start, cal), fmt_year(born, cal), tag), "participants")
                if is_int(died) and start > died:
                    report.warn(ev, "[[%s]] takes part in %s but died in %s%s" % (
                        who.name, fmt_year(start, cal), fmt_year(died, cal), tag), "participants")
        # location on the event's planets
        planets = {norm(t) for t in (link_target(p) for p in ev.get("planet") or []) if t}
        if planets:
            for loc in ev.get("location") or []:
                place = vault.resolve_link(loc)
                if place is None or place.type != "place":
                    continue
                lp = [t for t in (link_target(p) for p in place.get("planet") or []) if t]
                if norm(place.name) in planets:
                    continue
                if lp and not ({norm(t) for t in lp} & planets):
                    report.warn(ev, "location [[%s]] is on %s, which is not in the event's planets" % (
                        place.name, ", ".join(sorted(lp))), "location")
    # before / after ordering
    order = {}
    for ev in events:
        for key, sign in (("after", -1), ("before", 1)):
            for v in ev.get(key) or []:
                other = vault.resolve_link(v)
                if other is None or other.type != "event":
                    continue
                first, second = (other, ev) if sign < 0 else (ev, other)
                order.setdefault(first.rel, set()).add(second.rel)
                cal1, cal2 = first.get("calendar"), second.get("calendar")
                y1, y2 = vault.span(first)[0], vault.span(second)[0]
                if y1 is not None and y2 is not None and cal1 == cal2 and y2 < y1:
                    report.error(ev, "'%s' says [[%s]] (%s) comes before [[%s]] (%s), but the years say otherwise" % (
                        key, first.name, fmt_year(y1, cal1), second.name, fmt_year(y2, cal2)), key)
    # cycles
    state = {}

    def visit(n, stack):
        state[n] = 1
        for m in sorted(order.get(n, ())):
            if state.get(m) == 1:
                cyc = stack[stack.index(m):] + [m] if m in stack else [n, m]
                report.error(n, "before/after links form a loop: %s" % " -> ".join(
                    os.path.splitext(os.path.basename(c))[0] for c in cyc), "after")
            elif state.get(m) is None:
                visit(m, stack + [m])
        state[n] = 2

    for n in sorted(order):
        if state.get(n) is None:
            visit(n, [n])


def check_characters(vault, report):
    for ch in vault.of_type("character", "god"):
        born = ch.get("born")
        for p in ch.get("parents") or []:
            par = vault.resolve_link(p)
            if par is None:
                continue
            if par.rel == ch.rel:
                report.error(ch, "is listed as their own parent", "parents")
                continue
            pb, pd = par.get("born"), par.get("died")
            same_cal = par.get("calendar") == ch.get("calendar")
            if same_cal and is_int(born) and is_int(pb) and pb >= born:
                report.warn(ch, "parent [[%s]] is born in %d, not before the child (%d)" % (par.name, pb, born), "parents")
            if same_cal and is_int(born) and is_int(pd) and pd < born - 1:
                report.warn(ch, "parent [[%s]] died in %d, before the child was born (%d)" % (par.name, pd, born), "parents")
        for p in ch.get("partners") or []:
            par = vault.resolve_link(p)
            if par is None or par.parse_error:
                continue
            back = {norm(link_target(x) or "") for x in (par.get("partners") or [])}
            if norm(ch.name) not in back and not any(norm(a) in back for a in ch.get("aliases") or [] if isinstance(a, str)):
                report.warn(ch, "partner [[%s]] doesn't list this character in their 'partners'" % par.name, "partners")


def check_relationships(vault, report):
    seen = {}
    for rel in vault.of_type("relationship"):
        a, b = vault.resolve_link(rel.get("first")), vault.resolve_link(rel.get("second"))
        if a is None or b is None:
            continue
        if a.rel == b.rel:
            report.error(rel, "'first' and 'second' are the same note", "second")
            continue
        expected = "%s and %s" % (a.name, b.name)
        if norm(rel.name) != norm(expected):
            report.warn(rel, "should be named '%s'" % expected)
        pair = frozenset((a.rel, b.rel))
        if pair in seen:
            report.error(rel, "same pair as %s; merge them" % seen[pair])
        else:
            seen[pair] = rel.rel


def check_names(vault, report):
    """Two notes answering to the same name or alias."""
    reported = set()
    for key, notes in vault.by_name.items():
        uniq = sorted({n.rel for n in notes})
        if len(uniq) > 1 and tuple(uniq) not in reported:
            reported.add(tuple(uniq))
            report.error(uniq[0], "the name or alias '%s' is shared with %s; links are ambiguous" % (
                key, ", ".join(uniq[1:])))


def check_body_links(vault, report):
    for note in vault.notes:
        if note.parse_error:
            continue
        for line, target in body_links(note.body, note.body_line):
            if vault.resolve(target) is None and norm(target) not in vault.files \
                    and norm(target + ".md") not in vault.files:
                report.warn(note, "line %d links to [[%s]], which doesn't exist" % (line, target))


def check_templates(vault, report):
    for tpl in vault.templates:
        if tpl.parse_error:
            report.error(tpl, "properties can't be read (line %d): %s" % (tpl.parse_error.line, tpl.parse_error))
            continue
        ts = vault.type_schema(tpl.type)
        if ts is None:
            report.error(tpl, "template has unknown type %r" % tpl.type, "type")
            continue
        for key in tpl.props:
            if key not in ts["properties"]:
                report.error(tpl, "template property '%s' is not in the schema for %s notes" % (key, tpl.type), key)
            if key in ts["forbidden"]:
                report.error(tpl, "template uses forbidden property '%s'" % key, key)


# ---------------------------------------------------------------- docs

def render_docs(vault):
    s = vault.schema
    out = [DOCS_START, ""]
    out.append("Calendars: " + ", ".join("`%s` (%s)" % (k, v["planet"]) for k, v in s["calendars"].items())
               + ". Statuses: " + ", ".join("`%s`" % x for x in s["statuses"]) + ".")
    out.append("")

    def fmt(spec, key):
        t = spec["type"]
        if t in ("link", "links"):
            to = spec.get("to", ["*"])
            t = "%s → %s" % (t, "any" if "*" in to else ", ".join(to))
        elif t == "enum":
            vals = vault.enum_values(spec, key)
            if vals:
                t = "one of " + ", ".join(vals)
        elif t == "date" and spec.get("refines"):
            t = "date (in `%s`)" % spec["refines"]
        flags = []
        if spec.get("required"):
            flags.append("required")
        if spec.get("legacy"):
            flags.append("from WorldAnvil")
        return t, ", ".join(flags), spec.get("desc", "")

    out.append("### Every note")
    out.append("")
    out.append("| Property | Type | | Meaning |")
    out.append("|---|---|---|---|")
    for k, spec in s["common_properties"].items():
        t, f, d = fmt(spec, k)
        out.append("| `%s` | %s | %s | %s |" % (k, t, f, d))
    out.append("")
    for name, t in s["types"].items():
        out.append("### %s" % name)
        out.append("")
        bits = ["Folder: %s." % ("`%s/`" % t["folder"] if t["folder"] else "vault root")]
        if t.get("template"):
            bits.append("Template: `_templates/%s`." % t["template"])
        if t.get("inherits"):
            bits.append("Has every %s property, plus the ones below." % t["inherits"])
        if t.get("span"):
            bits.append("Exists from `%s` to `%s`." % (t["span"]["start"], t["span"]["end"]))
        if t.get("skip_common"):
            bits.append("Doesn't use: %s." % ", ".join("`%s`" % x for x in t["skip_common"]))
        if t.get("desc"):
            bits.insert(0, t["desc"])
        out.append(" ".join(bits))
        out.append("")
        if t.get("properties"):
            out.append("| Property | Type | | Meaning |")
            out.append("|---|---|---|---|")
            for k, spec in t["properties"].items():
                ty, f, d = fmt(spec, k)
                out.append("| `%s` | %s | %s | %s |" % (k, ty, f, d))
            out.append("")
        for k, why in t.get("forbidden", {}).items():
            out.append("- Never `%s`: %s" % (k, why))
        if t.get("forbidden"):
            out.append("")
    out.append(DOCS_END)
    return "\n".join(out)


def docs_path(vault):
    return os.path.join(vault.root, "Schema.md")


def check_docs(vault, report):
    p = docs_path(vault)
    if not os.path.exists(p):
        report.warn("Schema.md", "Schema.md is missing")
        return
    text = open(p, encoding="utf-8").read()
    m = re.search(re.escape(DOCS_START) + r".*?" + re.escape(DOCS_END), text, re.S)
    if not m:
        report.warn("Schema.md", "the generated tables are missing; run check_vault.py --write-docs")
    elif m.group(0) != render_docs(vault):
        report.warn("Schema.md", "the tables are out of date with schema.json; run check_vault.py --write-docs")


def write_docs(vault):
    p = docs_path(vault)
    text = open(p, encoding="utf-8").read()
    pat = re.compile(re.escape(DOCS_START) + r".*?" + re.escape(DOCS_END), re.S)
    new = render_docs(vault)
    text = pat.sub(lambda _: new, text) if pat.search(text) else text.rstrip() + "\n\n" + new + "\n"
    with open(p, "w", encoding="utf-8") as f:
        f.write(text)


# ---------------------------------------------------------------- main

def run(vault):
    report = Report()
    for note in vault.notes:
        check_note(vault, report, note)
    check_names(vault, report)
    check_events(vault, report)
    check_characters(vault, report)
    check_relationships(vault, report)
    check_body_links(vault, report)
    check_templates(vault, report)
    check_docs(vault, report)
    return report


def main(argv=None):
    ap = argparse.ArgumentParser(description="Check the vault against _tools/schema.json.")
    ap.add_argument("--json", action="store_true", help="print the report as JSON")
    ap.add_argument("--strict", action="store_true", help="fail on warnings too")
    ap.add_argument("--errors-only", action="store_true", help="hide warnings")
    ap.add_argument("--write-docs", action="store_true", help="regenerate the tables in Schema.md")
    ap.add_argument("--vault", default=None, help="vault folder (default: the one holding _tools)")
    args = ap.parse_args(argv)

    vault = Vault(args.vault) if args.vault else Vault()
    if args.write_docs:
        write_docs(vault)
        print("Schema.md tables regenerated.")
        vault = Vault(args.vault) if args.vault else Vault()

    report = run(vault)
    items = sorted(report.items, key=lambda i: (i["severity"] != ERROR, i["file"], i["property"] or "", i["message"]))
    if args.errors_only:
        items = [i for i in items if i["severity"] == ERROR]
    errors = sum(1 for i in report.items if i["severity"] == ERROR)
    warnings = sum(1 for i in report.items if i["severity"] == WARNING)

    if args.json:
        print(json.dumps({"schema_version": vault.schema["version"], "notes": len(vault.notes),
                          "errors": errors, "warnings": warnings, "items": items},
                         ensure_ascii=False, indent=2))
    else:
        current = None
        for i in items:
            if i["file"] != current:
                current = i["file"]
                print("\n" + current)
            print("  %-7s %s" % (i["severity"], i["message"]))
        print("\n%d notes checked: %d error(s), %d warning(s)." % (len(vault.notes), errors, warnings))

    failed = errors or (args.strict and warnings)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
